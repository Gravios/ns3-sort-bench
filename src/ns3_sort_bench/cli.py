"""CLI entry point for ns3-sort-bench.  Installed as `ns3-sort-bench`.

Commands:
    list-adapters        — print the adapter registry and availability
    list-scorers         — print the scorer registry
    list-contracts       — print each adapter's Contract (for CONTRACTS.md)
    dump-contracts       — render CONTRACTS.md to stdout
    run                  — delegate to runners.sorter_grid.main
    lattice              — delegate to runners.lattice.main
"""
from __future__ import annotations

import argparse
import sys


def _import_registries():
    """Populate the adapter + scorer registries (import-triggered side effects)."""
    import ns3_sort_bench.adapters  # noqa: F401
    import ns3_sort_bench.scorers   # noqa: F401


def cmd_list_adapters(args):
    _import_registries()
    from ns3_sort_bench import adapter_registry
    for name in sorted(adapter_registry):
        a = adapter_registry[name]
        ok, reason = a.available()
        state = "available" if ok else f"disabled: {reason}"
        print(f"  {name:30s}  v{a.version:20s}  {state}")
    print(f"\n{len(adapter_registry)} adapter(s) registered")


def cmd_list_scorers(args):
    _import_registries()
    from ns3_sort_bench import scorer_registry
    for name in sorted(scorer_registry):
        print(f"  {name}")
    print(f"\n{len(scorer_registry)} scorer(s) registered")


def cmd_list_contracts(args):
    _import_registries()
    from ns3_sort_bench import adapter_registry
    for name in sorted(adapter_registry):
        a = adapter_registry[name]
        c = a.contract
        if c is None:
            print(f"{name}: no contract declared"); continue
        print(f"\n{name}")
        print(f"  required: {list(c.yaml_fields_required)}")
        print(f"  optional: {list(c.yaml_fields_optional)}")
        print(f"  signal_space: {c.recording.signal_space}")
        print(f"  drift_aware: {c.capabilities.drift_aware}")
        print(f"  overlap_resolution: {c.capabilities.overlap_resolution}")
        print(f"  per_group_or_whole: {c.output.per_group_or_whole}")


def cmd_dump_contracts(args):
    _import_registries()
    from ns3_sort_bench import adapter_registry
    print("# ns3-sort-bench — adapter contracts\n")
    print("Auto-generated by `ns3-sort-bench dump-contracts`.  "
          "Edit the Contract objects in `src/ns3_sort_bench/adapters/*.py` and re-dump.\n")
    for name in sorted(adapter_registry):
        c = adapter_registry[name].contract
        if c:
            print(c.to_markdown())


def cmd_run(args):
    from ns3_sort_bench.runners import sorter_grid
    sys.argv = ["ns3-sort-bench run", *args.rest]
    return sorter_grid.main()


def cmd_lattice(args):
    from ns3_sort_bench.runners import lattice
    sys.argv = ["ns3-sort-bench lattice", *args.rest]
    return lattice.main()


def main(argv=None):
    ap = argparse.ArgumentParser(prog="ns3-sort-bench",
                                  description="Cross-sorter benchmark for ns3 sessions")
    sub = ap.add_subparsers(dest="cmd", required=True)
    sub.add_parser("list-adapters").set_defaults(fn=cmd_list_adapters)
    sub.add_parser("list-scorers").set_defaults(fn=cmd_list_scorers)
    sub.add_parser("list-contracts").set_defaults(fn=cmd_list_contracts)
    sub.add_parser("dump-contracts").set_defaults(fn=cmd_dump_contracts)
    r = sub.add_parser("run", help="run the sorter grid (see runners.sorter_grid)")
    r.add_argument("rest", nargs=argparse.REMAINDER); r.set_defaults(fn=cmd_run)
    l = sub.add_parser("lattice", help="run the fiber_deconv lattice ablation")
    l.add_argument("rest", nargs=argparse.REMAINDER); l.set_defaults(fn=cmd_lattice)

    args = ap.parse_args(argv)
    return args.fn(args) or 0


if __name__ == "__main__":
    sys.exit(main())
